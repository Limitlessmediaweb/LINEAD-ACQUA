const p = await ctx.newPage();
if (process.argv[2]) await p.addInitScript((css) => { const s = document.createElement("style"); s.textContent = css; document.documentElement.appendChild(s); }, process.argv[2]);
const cdp = await ctx.newCDPSession(p);
await cdp.send("Emulation.setCPUThrottlingRate", { rate: 4 });
